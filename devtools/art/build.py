# A 4 x 4 grid of 16-pixel swatches; a face takes one swatch whole, inset so no coordinate sits on
# a swatch's edge (Vanilla Wheels' rule: the cutout shader drops a face that samples the atlas's
# empty padding).
CELLS = {"body": (0, 0), "trim": (1, 0), "glass": (2, 0), "lamp": (3, 0),
         "prop": (0, 1), "metal": (1, 1), "hatch": (2, 1)}
COLOURS = {"body": (205, 205, 205), "trim": (60, 64, 70), "glass": (150, 200, 230), "lamp": (250, 240, 200),
           "prop": (176, 140, 60), "metal": (130, 136, 146), "hatch": (90, 96, 104)}


def atlas():
    noise = Noise(0x5B5B)
    px = canvas(64, 64)
    for name, (cx, cy) in CELLS.items():
        base = COLOURS[name]
        alpha = 160 if name == "glass" else 255
        for y in range(16):
            for x in range(16):
                px[cy * 16 + y][cx * 16 + x] = (*shade(base, int((noise.next() - 0.5) * 16)), alpha)
    return px


class ObjWriter:
    def __init__(self, what: str) -> None:
        self.lines = [f"# generated by devtools/art/build.py: {what}"]
        self.v = 0
        self.vt = 0

    def box(self, material, group, x0, y0, z0, x1, y1, z1):
        """A closed box from (x0,y0,z0) to (x1,y1,z1), six quads on one swatch, wound outward."""
        cx, cy = CELLS[material]
        inset = 0.02
        u0, v0 = cx / 4 + inset / 4, 1 - (cy + 1) / 4 + inset / 4
        u1, v1 = (cx + 1) / 4 - inset / 4, 1 - cy / 4 - inset / 4
        corners = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
        for c in corners:
            self.lines.append("v %.3f %.3f %.3f" % c)
        for (u, vv) in ((u0, v0), (u1, v0), (u1, v1), (u0, v1)):
            self.lines.append("vt %.4f %.4f" % (u, vv))
        base_v = self.v
        base_t = self.vt
        self.lines.append(f"usemtl {material}")
        self.lines.append(f"g {group}")
        faces = [(1, 4, 3, 2), (5, 6, 7, 8), (1, 2, 6, 5), (3, 4, 8, 7), (2, 3, 7, 6), (1, 5, 8, 4)]
        for f in faces:
            self.lines.append("f " + " ".join(f"{base_v + i}/{base_t + k + 1}" for k, i in enumerate(f)))
        self.v += 8
        self.vt += 4

    def text(self):
        return "\n".join(self.lines) + "\n"


def box_sub():
    """A hull 1.5 wide and tall, 4.5 long, its bow open round a window the pilot looks out of; a conning
    tower with a hatch; two lamps; a screw."""
    w = ObjWriter("the box submarine")
    w.box("body", "body", -12, 0, -36, 12, 24, 30)              # the hull, to the bow's bulkhead
    w.box("body", "body", -12, 0, 30, 12, 10, 36)               # the bow under the window
    w.box("body", "body", -12, 22, 30, 12, 24, 36)              # over it
    w.box("body", "body", -12, 10, 30, -8, 22, 36)              # beside it, left
    w.box("body", "body", 8, 10, 30, 12, 22, 36)                # and right
    w.box("glass", "window", -8, 10, 35.5, 8, 22, 36)           # the bow window
    w.box("body", "body", -6, 24, -6, 6, 34, 10)                # the conning tower
    w.box("hatch", "hatch", -4, 34, -2, 4, 35, 6)               # its hatch
    w.box("lamp", "lamps", -10, 2, 36, -6, 6, 36.5)             # left lamp
    w.box("lamp", "lamps", 6, 2, 36, 10, 6, 36.5)               # right lamp
    w.box("trim", "fin", -1, 4, -40, 1, 22, -36)                # the rudder
    w.box("metal", "propeller", -1, 11, -39, 1, 13, -36)        # the shaft
    w.box("prop", "propeller", -8, 11, -38.5, 8, 13, -37.5)     # the blades, across
    w.box("prop", "propeller", -1, 4, -38.5, 1, 20, -37.5)      # and up and down
    return w.text()


