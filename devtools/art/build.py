def torpedo_texture():
    """The torpedo's own 16 x 16: a grey body, a red warhead band, brass fins and screw."""
    grey, red, brass, dark = (150, 156, 164), (170, 40, 36), (186, 150, 70), (60, 62, 66)
    px = canvas(16, 16)
    noise = Noise(0x70F0)
    for y in range(16):
        for x in range(16):
            base = grey if y < 8 else red if y < 12 else brass if y < 15 else dark
            px[y][x] = (*shade(base, int((noise.next() - 0.5) * 12)), 255)
    return px


def torpedo_icon():
    """The torpedo for inventories, laid corner to corner: a grey body, a red warhead up-right, brass fins down-left."""
    grey, red, brass, dark = (150, 156, 164), (170, 40, 36), (186, 150, 70), (60, 62, 66)
    px = canvas(16, 16)
    for i in range(3, 13):
        for w in (-1, 0, 1):
            x, y = i + w, 15 - i
            if 0 <= x < 16 and 0 <= y < 16:
                px[y][x] = (*(red if i >= 11 else shade(grey, 20 if w < 0 else -25 if w > 0 else 0)), 255)
    px[2][13] = px[3][13] = (*shade(red, -30), 255)
    for (x, y) in ((2, 11), (2, 12), (3, 13), (4, 13), (1, 13), (2, 14)):
        px[y][x] = (*brass, 255)
    px[13][1] = (*dark, 255)
    return px


def cube(frm, to, u0, v0, u1, v1):
    face = {"uv": [u0, v0, u1, v1], "texture": "#all"}
    return {"from": frm, "to": to, "faces": {k: dict(face) for k in ("north", "south", "east", "west", "up", "down")}}


